/**
 * DSH (DeepSeek Harness) adapter — protocol shapes verified against the
 * official headless bundle (`@deepseek-ai/dsh-headless`, dsh
 * 0.1.6-alpha.1, one-shot task runner over dsh-base):
 *
 * - `dsh --profile headless --json [--session-id <id>] -- <task>` runs one
 *   task and exits; exit 0 = completed, 1 = aborted or errored.
 * - `--json` projects the run as newline-delimited events on stdout:
 *   `session` (sessionId + cwd) → `status` (turn/step phases; `step_end`
 *   carries that model request's usage) → `text` / `thinking` (projected
 *   from *committed* assistant messages, so retried attempts never reach
 *   the stream) → `tool_call` / `tool_result` (paired by callId) →
 *   `final` (the same lossless answer the default mode prints). A failure
 *   raised outside a turn writes an `error` event and ends without
 *   `final`; a failure inside a turn still ends with `final` (often
 *   empty) — exit code and `turn_end` reason are the failure signal.
 * - `--session-id` adopts the persisted Session with that id — the same
 *   ids the local session discovery lists. The one-shot runner composes
 *   no agent preset, so it refuses every session that carries one —
 *   i.e. sessions from the desktop/web surfaces — as well as subagent /
 *   forked sessions and sessions whose recorded cwd differs from the
 *   run's working directory. Those refusals happen before the task runs
 *   and keep DSH's own message; such sessions still adopt into
 *   AgentFabric (history projection) and continue via handoff.
 * - Runs on the harness's own DeepSeek account (harness-native, v6 §2);
 *   AgentFabric binds no Provider/Model. The task runs in the profile's
 *   own model selection and sandbox defaults.
 */

interface DshEvent {
  type?: string;
  sessionId?: unknown;
  cwd?: unknown;
  phase?: unknown;
  turn?: unknown;
  step?: unknown;
  usage?: DshUsage;
  reason?: { kind?: unknown };
  text?: unknown;
  callId?: unknown;
  tool?: unknown;
  input?: unknown;
  status?: unknown;
  result?: unknown;
  message?: unknown;
  [key: string]: unknown;
}

export function dshBin(): string {
  return process.env.AGENTFABRIC_DSH_BIN ?? "dsh";
}

/** $DSH_HOME resolution mirrors the harness's own launcher. */
function dshHome(): string {
  return process.env.DSH_HOME ?? join(homedir(), ".dsh");
}

/**
 * The headless bundle's profile directory. DSH boots profiles from
 * $DSH_HOME/profiles; a missing one fails loudly in the harness itself
 * ("create it with 'dsh plugin --profile <name> add <package>'") — the
 * auth check surfaces the same remedy before a run is attempted.
 */
export function dshHeadlessProfileDir(): string {
  return join(dshHome(), "profiles", "headless");
}

/**
 * DSH harness capabilities (spec v1 §17): native sessions with resume,
 * streamed events, workspace-aware. Handoff summaries are generated by
 * AgentFabric (assisted) — the headless runner has no summary mode.
 */
export const dshCapabilities: Partial<RuntimeCapability> = {
  supportsNativeSession: true,
  supportsNativeResume: true,
  supportsStreamingEvents: true,
  supportsHandoffGeneration: false,
  supportsWorkspace: true,
  supportsInteractiveExecution: false,
};

/**
 * Containerized DSH has no official runtime image; without a configured
 * `image` the effective-capability computation narrows these to "cannot
 * run" and the adapter refuses to start (same contract as pi, v3 §10).
 * The opaque native state (~/.dsh: sessions, profiles, credentials) is
 * what must be mounted for Containerized Native Resume.
 */
export const dshNativeStateMountPath = "/root/.dsh";

