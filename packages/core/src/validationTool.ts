/**
 * The generated verdict tool (v12 §5.1).
 *
 * The Validation Agent needs a deterministic way to submit its verdict.
 * AgentFabric's MCP configuration is not yet consumed by every harness, so
 * the tool is delivered as a **script the judge runs with `node`** — the one
 * channel every harness provably has, since the judge must be able to run
 * build/test commands anyway.
 *
 * The script:
 * - parses `--passed|--failed`, `--summary`, `--unmet`, `--evidence` flags,
 * - validates the payload against the same contract the supervisor applies
 *   (`parseVerdictPayload`), so the judge gets immediate feedback and can
 *   correct itself,
 * - writes `verdict.json` into the run's verdict output directory and
 *   appends one audit line to `verdict-calls.jsonl`,
 * - exits 0 on success, 2 on an invalid payload, 1 on an I/O failure.
 *
 * The file is generated per run by provisioning; its content depends only on
 * the Node standard library and is **ESM** — the file is `.mjs`, so Node
 * always parses it as a module regardless of any package.json around it.
 */

/**
 * The script source. `outputDir` is baked in per run so the judge does not
 * have to know (or guess) where the platform reads the verdict from.
 */
export function validationToolScript(outputDir: string): string {
  return `#!/usr/bin/env node
// Generated by AgentFabric — the validation verdict tool (v12 §5.1).
// Usage: node validation-tool.mjs --passed|--failed --summary <s> [--unmet <s> ...] --evidence <s> [--evidence <s> ...]
import fs from "node:fs";
import path from "node:path";

const OUTPUT_DIR = ${JSON.stringify(outputDir)};
const VERDICT_FILE = path.join(OUTPUT_DIR, "verdict.json");
const CALLS_FILE = path.join(OUTPUT_DIR, "verdict-calls.jsonl");

function fail(message, code) {
  process.stderr.write("verdict rejected: " + message + "\\n");
  process.exit(code);
}

function parseArgs(argv) {
  const out = { passed: undefined, summary: undefined, unmet: [], evidence: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--passed") out.passed = true;
    else if (arg === "--failed") out.passed = false;
    else if (arg === "--summary") out.summary = argv[++i];
    else if (arg === "--unmet") out.unmet.push(argv[++i]);
    else if (arg === "--evidence") out.evidence.push(argv[++i]);
    else fail("unknown argument: " + arg, 2);
  }
  return out;
}

const raw = parseArgs(process.argv.slice(2));
if (typeof raw.passed !== "boolean") fail("one of --passed or --failed is required", 2);
if (typeof raw.summary !== "string" || !raw.summary.trim()) fail("--summary must be a non-empty string", 2);
if (raw.unmet.some((u) => typeof u !== "string" || !u.trim())) fail("--unmet must be non-empty strings", 2);
if (raw.evidence.length === 0) fail("at least one --evidence entry is required", 2);
if (raw.evidence.some((e) => typeof e !== "string" || !e.trim())) fail("--evidence must be non-empty strings", 2);
if (!raw.passed && raw.unmet.length === 0) fail("a failure verdict must name at least one --unmet requirement", 2);

const verdict = {
  passed: raw.passed,
  summary: raw.summary.trim(),
  unmet: raw.unmet.map((u) => u.trim()),
  evidence: raw.evidence.map((e) => e.trim()),
};

try {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  fs.writeFileSync(VERDICT_FILE, JSON.stringify(verdict, null, 2) + "\\n");
  fs.appendFileSync(CALLS_FILE, JSON.stringify({ at: new Date().toISOString(), verdict }) + "\\n");
} catch (err) {
  fail("could not write the verdict: " + (err && err.message ? err.message : String(err)), 1);
}

process.stdout.write(
  "verdict recorded: " + (verdict.passed ? "PASSED" : "FAILED") + " — " + verdict.summary + "\\n"
);
process.exit(0);
`;
}

/** Name of the generated tool file inside the provisioning directory. */
export const VALIDATION_TOOL_FILE_NAME = "validation-tool.mjs";
/** Name of the verdict file inside the output directory. */
export const VALIDATION_VERDICT_FILE_NAME = "verdict.json";
