const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { zh, en };

/**
 * Run/task state → its label. The state value itself stays what the API says
 * (it is also the badge's class name); only the text shown changes with the
 * language. An unknown state is displayed as-is.
 */
export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

/**
 * Display label for a status value read from a record: translated when the
 * value is known, passed through unchanged otherwise (an unknown value is data,
 * not a translation problem). Never feeds back into a request.
 */
export function statusLabel(t: Translate, status?: string | null): string {
  if (!status) return "—";
  const key = STATUS_KEYS[status];
  return key ? t(key) : status;
}

