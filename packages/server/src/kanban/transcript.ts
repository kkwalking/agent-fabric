/**
 * Persisted transcript of one ACP board session (v13).
 *
 * The projector's item list is the board's own committed projection of the
 * ACP update stream. It is written after each change (debounced while chunks
 * stream) and again at every turn boundary, so a restarted server can still
 * show the conversation the user watched. One JSON document per session, kept
 * beside the store rather than inside db.json: a long transcript must not turn
 * every unrelated store mutation into a multi-megabyte rewrite.
 *
 * The file is a cache of our own projection, not a second source of truth:
 * when it is missing or unreadable the session simply has no saved transcript
 * (old sessions predate it), and the agent's own session is still resumable.
 * Files are named by session id, which is generated by `newId` (safe chars).
 */
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { ID } from "@agentfabric/core";
import type { ChatItem } from "./acpChat.js";

/** Bumped when the document shape changes; older documents read as absent. */
const TRANSCRIPT_VERSION = 1;

const SAFE_SESSION_ID = /^[A-Za-z0-9_-]+$/;

interface TranscriptDocument {
  version: number;
  sessionId: string;
  updatedAt: string;
  items: ChatItem[];
}

export interface LoadedTranscript {
  items: ChatItem[];
  /** False when no (valid) document exists for this session. */
  found: boolean;
}

/** The chat item kinds the projector can have produced. */
const ITEM_KINDS = new Set(["user", "agent", "reasoning", "tool", "error"]);

function isChatItem(value: unknown): value is ChatItem {
  if (typeof value !== "object" || value === null) return false;
  const item = value as { id?: unknown; kind?: unknown; at?: unknown };
  return (
    typeof item.id === "string" &&
    item.id !== "" &&
    typeof item.kind === "string" &&
    ITEM_KINDS.has(item.kind) &&
    typeof item.at === "string"
  );
}

export class KanbanTranscriptStore {
  private readonly dir: string;

  constructor(dataDir: string) {
    this.dir = join(dataDir, "kanban-chats");
  }

  path(sessionId: ID): string {
    if (!SAFE_SESSION_ID.test(sessionId)) {
      throw new Error(`Invalid board session id for a transcript: ${sessionId}`);
    }
    return join(this.dir, `${sessionId}.json`);
  }

  /**
   * Reads one session's transcript. A malformed document is treated as absent
   * rather than partially repaired: a torn or hand-edited file is not data the
   * board should guess about (AGENTS.md: no read-time rescue).
   */
  async load(sessionId: ID): Promise<LoadedTranscript> {
    let raw: string;
    try {
      raw = await readFile(this.path(sessionId), "utf8");
    } catch {
      return { items: [], found: false };
    }
    return parseTranscript(raw, sessionId);
  }

  async save(sessionId: ID, items: readonly ChatItem[]): Promise<void> {
    const file = this.path(sessionId);
    await mkdir(dirname(file), { recursive: true });
    const tmp = `${file}.tmp`;
    await writeFile(tmp, serializeTranscript(sessionId, items), { mode: 0o600 });
    await rename(tmp, file);
  }

  /**
   * Synchronous variant for process shutdown: the caller exits immediately
   * afterwards, so the write may not wait on the event loop.
   */
  saveSync(sessionId: ID, items: readonly ChatItem[]): void {
    const file = this.path(sessionId);
    mkdirSync(dirname(file), { recursive: true });
    const tmp = `${file}.tmp`;
    writeFileSync(tmp, serializeTranscript(sessionId, items), { mode: 0o600 });
    renameSync(tmp, file);
  }

  async remove(sessionId: ID): Promise<void> {
    await rm(this.path(sessionId), { force: true });
  }

  removeSync(sessionId: ID): void {
    rmSync(this.path(sessionId), { force: true });
  }
}

function serializeTranscript(sessionId: ID, items: readonly ChatItem[]): string {
  const document: TranscriptDocument = {
    version: TRANSCRIPT_VERSION,
    sessionId,
    updatedAt: new Date().toISOString(),
    items: items as ChatItem[],
  };
  return JSON.stringify(document);
}

function parseTranscript(raw: string, sessionId: ID): LoadedTranscript {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    console.warn(`[agent-fabric] ignoring unreadable board transcript for ${sessionId}`);
    return { items: [], found: false };
  }
  if (typeof parsed !== "object" || parsed === null) return { items: [], found: false };
  const document = parsed as Partial<TranscriptDocument>;
  if (document.version !== TRANSCRIPT_VERSION || document.sessionId !== sessionId) {
    return { items: [], found: false };
  }
  if (!Array.isArray(document.items) || !document.items.every(isChatItem)) {
    console.warn(`[agent-fabric] ignoring malformed board transcript for ${sessionId}`);
    return { items: [], found: false };
  }
  return { items: document.items, found: true };
}
